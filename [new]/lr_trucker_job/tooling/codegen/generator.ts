export function findStaleGeneratedModuleArtifacts(
  existingPaths: readonly string[],
  expectedPaths: Iterable<string>
): string[] {
  const expected = new Set(expectedPaths);
  return existingPaths.filter(file => !expected.has(file)).sort();
}

export function findDuplicateValues(values: readonly string[]): string[] {
  const seen = new Set<string>();
  const duplicates = new Set<string>();
  for (const value of values) {
    if (seen.has(value)) duplicates.add(value);
    seen.add(value);
  }
  return [...duplicates].sort();
}

function entries<T>(record: Readonly<Record<string, T>>): [string, T][] {
  return Object.entries(record).sort(([left], [right]) => left.localeCompare(right));
}

function pascal(value: string): string {
  return value
    .replace(/^[a-z]/, letter => letter.toUpperCase())
    .replace(/_([a-z])/g, (_match, letter: string) => letter.toUpperCase());
}

function camel(value: string): string {
  const identifier = pascal(value);
  return identifier[0]!.toLowerCase() + identifier.slice(1);
}

function sortJson(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortJson);
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, item]) => [key, sortJson(item)])
    );
  }
  return value;
}

function toLua(value: unknown, level = 0): string {
  if (value === null) return 'LR.JSON_NULL';
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    if (value.length === 0) return '{}';
    const indent = '  '.repeat(level + 1);
    return `{\n${value.map(item => `${indent}${toLua(item, level + 1)},`).join('\n')}\n${'  '.repeat(level)}}`;
  }
  if (value !== null && typeof value === 'object') {
    const sorted = Object.entries(value).sort(([left], [right]) => left.localeCompare(right));
    if (sorted.length === 0) return '{}';
    const indent = '  '.repeat(level + 1);
    return `{\n${sorted
      .map(([key, item]) => `${indent}[${JSON.stringify(key)}] = ${toLua(item, level + 1)},`)
      .join('\n')}\n${'  '.repeat(level)}}`;
  }
  throw new TypeError(`Cannot generate Lua for ${typeof value}`);
}

function sideContract(contract: ModuleContractInput, side: Side): JsonRecord {
  const base: JsonRecord = {version: CONTRACT_VERSION, id: contract.id};
  if (side === 'client') {
    return {
      ...base,
      state: contract.state,
      nui: contract.nui,
      net: contract.net,
      exports: {client: contract.exports.client},
    };
  }
  if (side === 'server') {
    return {
      ...base,
      net: contract.net,
      exports: {server: contract.exports.server},
    };
  }
  return {
    ...base,
    net: contract.net,
    exports: contract.exports,
  };
}

function renderRuntimeContract(contract: ModuleContractInput, side: Side): string {
  return `${HEADER_LUA}LR = LR or {}\nLR.Generated = LR.Generated or {}\nLR.Generated.Contracts = LR.Generated.Contracts or {}\n\nLR.Generated.Contracts[${JSON.stringify(contract.id)}] = LR.Schema.CompileContract(${toLua(
    sideContract(contract, side)
  )})\n`;
}

interface LuaTypeCollector {
  readonly definitions: Map<string, string>;
}

function literalLuaType(value: unknown): string {
  if (typeof value === 'string') return JSON.stringify(value);
  if (typeof value === 'boolean' || typeof value === 'number') return String(value);
  if (value === null) return 'nil';
  throw new TypeError(`Unsupported Lua literal type: ${typeof value}`);
}

function schemaLuaType(
  schema: ContractSchema,
  suggestedName: string,
  collector: LuaTypeCollector
): string {
  const raw = schema as unknown as JsonRecord;
  if (raw.const !== undefined) return literalLuaType(raw.const);
  if (Array.isArray(raw.enum)) return raw.enum.map(literalLuaType).join('|');
  if (Array.isArray(raw.anyOf)) {
    return raw.anyOf
      .map((candidate, index) =>
        schemaLuaType(candidate as ContractSchema, `${suggestedName}Variant${index + 1}`, collector)
      )
      .join('|');
  }

  if (raw.type === 'string') return 'string';
  if (raw.type === 'integer') return 'integer';
  if (raw.type === 'number') return 'number';
  if (raw.type === 'boolean') return 'boolean';
  if (raw.type === 'null') return 'nil';
  if (raw.type === 'array') {
    return `${schemaLuaType(raw.items as ContractSchema, `${suggestedName}Item`, collector)}[]`;
  }
  if (raw.type === 'object') {
    const properties = (raw.properties ?? {}) as Record<string, ContractSchema>;
    const patternProperties = (raw.patternProperties ?? {}) as Record<string, ContractSchema>;
    if (Object.keys(properties).length === 0 && Object.keys(patternProperties).length > 0) {
      const valueSchema = Object.values(patternProperties)[0]!;
      return `table<string, ${schemaLuaType(valueSchema, `${suggestedName}Value`, collector)}>`;
    }
    if (!collector.definitions.has(suggestedName)) {
      collector.definitions.set(suggestedName, '');
      const required = new Set((raw.required ?? []) as string[]);
      const lines = [`---@class ${suggestedName}`];
      for (const [name, propertySchema] of entries(properties)) {
        const fieldType = schemaLuaType(
          propertySchema,
          `${suggestedName}${pascal(name)}`,
          collector
        );
        lines.push(`---@field ${name}${required.has(name) ? '' : '?'} ${fieldType}`);
      }
      collector.definitions.set(suggestedName, lines.join('\n'));
    }
    return suggestedName;
  }
  throw new TypeError(`Unsupported generated schema type: ${String(raw.type)}`);
}

function collectSharedTypes(contract: ModuleContractInput, collector: LuaTypeCollector): void {
  const prefix = `LR${pascal(contract.id)}`;
  for (const [direction, schemas] of entries(contract.net.events)) {
    for (const [name, schema] of entries(schemas)) {
      schemaLuaType(schema, `${prefix}Net${pascal(direction)}${pascal(name)}Payload`, collector);
    }
  }
  for (const [direction, endpoints] of entries(contract.net.rpc)) {
    for (const [name, endpoint] of entries(endpoints)) {
      schemaLuaType(endpoint.request, `${prefix}Net${pascal(direction)}${pascal(name)}Request`, collector);
      schemaLuaType(endpoint.response, `${prefix}Net${pascal(direction)}${pascal(name)}Response`, collector);
    }
  }
}

function sideTypeCollector(contract: ModuleContractInput): LuaTypeCollector {
  const shared: LuaTypeCollector = {definitions: new Map()};
  collectSharedTypes(contract, shared);
  return {
    definitions: new Map(
      [...shared.definitions.keys()].map(name => [name, ''] as const)
    ),
  };
}

function renderDefinitions(collector: LuaTypeCollector): string {
  return [...collector.definitions.values()].filter(Boolean).join('\n\n');
}

function rpcEndpointTypes(
  endpoint: RpcContract,
  baseName: string,
  collector: LuaTypeCollector,
  mode: 'call' | 'handle',
  source = false,
  authorizeRequired = false
): string {
  const request = schemaLuaType(endpoint.request, `${baseName}Request`, collector);
  const response = schemaLuaType(endpoint.response, `${baseName}Response`, collector);
  if (mode === 'call') {
    return source
      ? `{ Call: fun(self, source: integer, request: ${request}): ${response} }`
      : `{ Call: fun(self, request: ${request}): ${response} }`;
  }
  if (source && authorizeRequired) {
    return `{ Handle: fun(self, handler: { Authorize: fun(source: integer, request: ${request}): boolean, Execute: fun(source: integer, request: ${request}): ${response} }): fun() }`;
  }
  if (source) {
    return `{ Handle: fun(self, handler: fun(source: integer, request: ${request}): ${response}): fun() }`;
  }
  return `{ Handle: fun(self, handler: fun(request: ${request}): ${response}): fun() }`;
}

function renderSharedTypes(contract: ModuleContractInput): string {
  const collector: LuaTypeCollector = {definitions: new Map()};
  collectSharedTypes(contract, collector);
  const definitions = renderDefinitions(collector);
  return definitions === '' ? `${HEADER_META.trimEnd()}\n` : `${HEADER_META}${definitions}\n`;
}

function renderClientTypes(contract: ModuleContractInput): string {
  const collector = sideTypeCollector(contract);
  const prefix = `LR${pascal(contract.id)}`;
  const nuiClass = `LRClient${pascal(contract.id)}Nui`;
  const stateClass = `${nuiClass}State`;
  const eventClass = `${nuiClass}Events`;
  const rpcClass = `${nuiClass}Rpc`;
  const netClass = `LRClient${pascal(contract.id)}Net`;
  const netEventClass = `${netClass}Events`;
  const netRpcClass = `${netClass}Rpc`;
  const publicClass = `LRClient${pascal(contract.id)}Public`;
  const publicHandlersClass = `${publicClass}Handlers`;
  const publicExternalClass = `${publicClass}External`;
  const stateLines = [`---@class ${stateClass}`];
  const stateEndpointLines: string[] = [];
  for (const [name, definition] of entries(contract.state)) {
    const typeName = schemaLuaType(definition.schema, `${prefix}State${pascal(name)}`, collector);
    const endpointClass = `${nuiClass}State${pascal(name)}`;
    const methods = [
      `---@class ${endpointClass}`,
      `---@field Get fun(self): ${typeName}`,
      `---@field Watch fun(self, handler: fun(value: ${typeName}, previous?: ${typeName})): fun()`,
    ];
    methods.push(`---@field Set fun(self, value: ${typeName})`);
    if (definition.patch !== undefined) {
      const patchType = schemaLuaType(
        definition.patch,
        `${prefix}State${pascal(name)}Patch`,
        collector
      );
      methods.push(`---@field Patch fun(self, patch: ${patchType})`);
    }
    stateEndpointLines.push(methods.join('\n'));
    stateLines.push(`---@field ${name} ${endpointClass}`);
  }
  const eventLines = [`---@class ${eventClass}`];
  for (const [name, schema] of entries(contract.nui.events.toNui)) {
    const payload = schemaLuaType(schema, `${prefix}Nui${pascal(name)}Payload`, collector);
    eventLines.push(`---@field ${name} { Emit: fun(self, payload: ${payload}): boolean }`);
  }
  for (const [name, schema] of entries(contract.nui.events.toClient)) {
    const payload = schemaLuaType(schema, `${prefix}Nui${pascal(name)}Payload`, collector);
    eventLines.push(`---@field ${name} { On: fun(self, handler: fun(payload: ${payload})): fun() }`);
  }
  const rpcLines = [`---@class ${rpcClass}`];
  for (const [name, endpoint] of entries(contract.nui.rpc.toNui)) {
    rpcLines.push(`---@field ${name} ${rpcEndpointTypes(endpoint, `${prefix}Nui${pascal(name)}`, collector, 'call')}`);
  }
  for (const [name, endpoint] of entries(contract.nui.rpc.toClient)) {
    rpcLines.push(`---@field ${name} ${rpcEndpointTypes(endpoint, `${prefix}Nui${pascal(name)}`, collector, 'handle')}`);
  }
  const netEventLines = [`---@class ${netEventClass}`];
  const netRpcLines = [`---@class ${netRpcClass}`];
  for (const [name, schema] of entries(contract.net.events.clientToServer)) {
    const payload = schemaLuaType(
      schema,
      `${prefix}NetClientToServer${pascal(name)}Payload`,
      collector
    );
    netEventLines.push(`---@field ${name} { Emit: fun(self, payload: ${payload}) }`);
  }
  for (const [name, schema] of entries(contract.net.events.serverToClient)) {
    const payload = schemaLuaType(
      schema,
      `${prefix}NetServerToClient${pascal(name)}Payload`,
      collector
    );
    netEventLines.push(
      `---@field ${name} { On: fun(self, handler: fun(payload: ${payload})): fun() }`
    );
  }
  for (const [name, endpoint] of entries(contract.net.rpc.clientToServer)) {
    netRpcLines.push(
      `---@field ${name} ${rpcEndpointTypes(endpoint, `${prefix}NetClientToServer${pascal(name)}`, collector, 'call')}`
    );
  }
  for (const [name, endpoint] of entries(contract.net.rpc.serverToClient)) {
    netRpcLines.push(
      `---@field ${name} ${rpcEndpointTypes(endpoint, `${prefix}NetServerToClient${pascal(name)}`, collector, 'handle')}`
    );
  }
  const publicHandlerLines = [`---@class ${publicHandlersClass}`];
  const publicAuthorizationLines: string[] = [];
  const publicExternalLines = [`---@class ${publicExternalClass}`];
  for (const [name, endpoint] of entries(contract.exports.client)) {
    const baseName = `${prefix}ExportClient${pascal(name)}`;
    const request = schemaLuaType(endpoint.request, `${baseName}Request`, collector);
    const response = schemaLuaType(endpoint.response, `${baseName}Response`, collector);
    if (endpoint.mutating === true) {
      const handlerClass = `${publicClass}${pascal(name)}Handler`;
      publicAuthorizationLines.push(
        `---@class ${handlerClass}\n---@field Authorize fun(invokingResource: string, request: ${request}): boolean\n---@field Execute fun(invokingResource: string, request: ${request}): ${response}`
      );
      publicHandlerLines.push(`---@field ${name} ${handlerClass}`);
    } else {
      publicHandlerLines.push(`---@field ${name} fun(request: ${request}): ${response}`);
    }
    publicExternalLines.push(
      `---@field ${pascal(name)} fun(self, request: ${request}): ${response}`
    );
  }
  const publicLines = [
    `---@class ${publicClass}`,
    `---@field Register fun(self, handlers: ${publicHandlersClass}): fun()`,
  ];
  const accessor = pascal(contract.id);
  return `${HEADER_META}${renderDefinitions(collector)}\n\n${stateEndpointLines.join('\n\n')}\n\n${stateLines.join('\n')}\n\n${eventLines.join('\n')}\n\n${rpcLines.join('\n')}\n\n---@class ${nuiClass}\n---@field state ${stateClass}\n---@field events ${eventClass}\n---@field rpc ${rpcClass}\n\n${netEventLines.join('\n')}\n\n${netRpcLines.join('\n')}\n\n---@class ${netClass}\n---@field events ${netEventClass}\n---@field rpc ${netRpcClass}\n\n${publicAuthorizationLines.join('\n\n')}\n\n${publicHandlerLines.join('\n')}\n\n${publicExternalLines.join('\n')}\n\n${publicLines.join('\n')}\n\n---@class LRClient.Nui\n---@field ${accessor} fun(): ${nuiClass}\n\n---@class LRClient.Net\n---@field ${accessor} ${netClass}\n\n---@class LRClient.Public\n---@field ${accessor} ${publicClass}\n\n---@class LRClient.External\n---@field ${accessor} fun(resourceName: string): ${publicExternalClass}\n`;
}

function renderServerTypes(contract: ModuleContractInput): string {
  const collector = sideTypeCollector(contract);
  const prefix = `LR${pascal(contract.id)}`;
  const netClass = `LRServer${pascal(contract.id)}Net`;
  const netEventClass = `${netClass}Events`;
  const netRpcClass = `${netClass}Rpc`;
  const publicClass = `LRServer${pascal(contract.id)}Public`;
  const publicHandlersClass = `${publicClass}Handlers`;
  const publicExternalClass = `${publicClass}External`;
  const eventLines = [`---@class ${netEventClass}`];
  const rpcLines = [`---@class ${netRpcClass}`];
  const handlerLines: string[] = [];
  for (const [name, schema] of entries(contract.net.events.clientToServer)) {
    const payload = schemaLuaType(schema, `${prefix}NetClientToServer${pascal(name)}Payload`, collector);
    eventLines.push(`---@field ${name} { Handle: fun(self, handler: fun(source: integer, payload: ${payload})): fun() }`);
  }
  for (const [name, schema] of entries(contract.net.events.serverToClient)) {
    const payload = schemaLuaType(schema, `${prefix}NetServerToClient${pascal(name)}Payload`, collector);
    eventLines.push(`---@field ${name} { Emit: fun(self, source: integer, payload: ${payload}) }`);
  }
  for (const [name, endpoint] of entries(contract.net.rpc.clientToServer)) {
    const baseName = `${prefix}NetClientToServer${pascal(name)}`;
    if (endpoint.mutating === true) {
      const request = schemaLuaType(endpoint.request, `${baseName}Request`, collector);
      const response = schemaLuaType(endpoint.response, `${baseName}Response`, collector);
      const handlerClass = `LRServer${pascal(contract.id)}Net${pascal(name)}Handler`;
      handlerLines.push(
        `---@class ${handlerClass}\n---@field Authorize fun(source: integer, request: ${request}): boolean\n---@field Execute fun(source: integer, request: ${request}): ${response}`
      );
      rpcLines.push(`---@field ${name} { Handle: fun(self, handler: ${handlerClass}): fun() }`);
    } else {
      rpcLines.push(`---@field ${name} ${rpcEndpointTypes(endpoint, baseName, collector, 'handle', true)}`);
    }
  }
  for (const [name, endpoint] of entries(contract.net.rpc.serverToClient)) {
    rpcLines.push(`---@field ${name} ${rpcEndpointTypes(endpoint, `${prefix}NetServerToClient${pascal(name)}`, collector, 'call', true)}`);
  }
  const publicHandlerLines = [`---@class ${publicHandlersClass}`];
  const publicAuthorizationLines: string[] = [];
  const publicExternalLines = [`---@class ${publicExternalClass}`];
  for (const [name, endpoint] of entries(contract.exports.server)) {
    const baseName = `${prefix}ExportServer${pascal(name)}`;
    const request = schemaLuaType(endpoint.request, `${baseName}Request`, collector);
    const response = schemaLuaType(endpoint.response, `${baseName}Response`, collector);
    if (endpoint.mutating === true) {
      const handlerClass = `${publicClass}${pascal(name)}Handler`;
      publicAuthorizationLines.push(
        `---@class ${handlerClass}\n---@field Authorize fun(invokingResource: string, request: ${request}): boolean\n---@field Execute fun(invokingResource: string, request: ${request}): ${response}`
      );
      publicHandlerLines.push(`---@field ${name} ${handlerClass}`);
    } else {
      publicHandlerLines.push(`---@field ${name} fun(request: ${request}): ${response}`);
    }
    publicExternalLines.push(
      `---@field ${pascal(name)} fun(self, request: ${request}): ${response}`
    );
  }
  const publicLines = [
    `---@class ${publicClass}`,
    `---@field Register fun(self, handlers: ${publicHandlersClass}): fun()`,
  ];
  const accessor = pascal(contract.id);
  return `${HEADER_META}${renderDefinitions(collector)}\n\n${handlerLines.join('\n\n')}\n\n${eventLines.join('\n')}\n\n${rpcLines.join('\n')}\n\n---@class ${netClass}\n---@field events ${netEventClass}\n---@field rpc ${netRpcClass}\n\n${publicAuthorizationLines.join('\n\n')}\n\n${publicHandlerLines.join('\n')}\n\n${publicExternalLines.join('\n')}\n\n${publicLines.join('\n')}\n\n---@class LRServer.Net\n---@field ${accessor} ${netClass}\n\n---@class LRServer.Public\n---@field ${accessor} ${publicClass}\n\n---@class LRServer.External\n---@field ${accessor} fun(resourceName: string): ${publicExternalClass}\n`;
}

function renderContractDeclaration(
  contract: ModuleContractInput,
  exported: boolean
): string {
  const serialized = JSON.stringify(sortJson(contract), null, 2);
  return `${exported ? 'export ' : ''}const ${camel(contract.id)}Contract = defineModuleContract(${serialized} as const);`;
}

function renderContractModule(contract: ModuleContractInput): string {
  const contractName = `${pascal(contract.id)}Contract`;
  return `${HEADER_TS}import {defineModuleContract} from '../index.ts';\n\n${renderContractDeclaration(contract, true)}\n\nexport type ${contractName} = typeof ${camel(contract.id)}Contract;\n`;
}

function renderContractModuleIndex(contracts: readonly ModuleContractInput[]): string {
  const imports = contracts.map(
    contract =>
      `import {${camel(contract.id)}Contract} from './${contract.id}.contract.ts';`
  );
  const exports = contracts.map(contract => {
    const value = `${camel(contract.id)}Contract`;
    return `export {${value}, type ${pascal(contract.id)}Contract} from './${contract.id}.contract.ts';`;
  });
  const values = contracts.map(contract => `  ${camel(contract.id)}Contract,`).join('\n');
  return `${HEADER_TS}${imports.join('\n')}${imports.length > 0 ? '\n\n' : ''}${exports.join('\n')}${exports.length > 0 ? '\n\n' : ''}export const moduleContracts = Object.freeze([\n${values}${values.length > 0 ? '\n' : ''}] as const);\n`;
}

function browserContract(contract: ModuleContractInput): ModuleContractInput {
  return {
    id: contract.id,
    state: contract.state,
    nui: contract.nui,
    net: {
      events: {clientToServer: {}, serverToClient: {}},
      rpc: {clientToServer: {}, serverToClient: {}},
    },
    exports: {client: {}, server: {}},
  };
}

function renderWeb(contracts: readonly ModuleContractInput[]): string {
  const typeExports: string[] = [];
  for (const contract of contracts) {
    const contractName = pascal(contract.id);
    for (const [name] of entries(contract.state)) {
      typeExports.push(
        `export type ${contractName}${pascal(name)} = ContractStatic<typeof generatedContracts.${contract.id}.state.${name}.schema>;`
      );
    }
  }
  const declarations = contracts.map(contract =>
    renderContractDeclaration(browserContract(contract), false)
  );
  const registry = contracts
    .map(contract => `  ${JSON.stringify(contract.id)}: ${camel(contract.id)}Contract,`)
    .join('\n');
  return `${HEADER_TS}import {defineModuleContract, type ContractStatic} from '@lr/contracts';\n\n${declarations.join('\n\n')}${declarations.length > 0 ? '\n\n' : ''}export const generatedContracts = Object.freeze({\n${registry}${registry.length > 0 ? '\n' : ''}} as const);\n\nexport type GeneratedContracts = typeof generatedContracts;\n${typeExports.join('\n')}\n`;
}

function renderDocs(contracts: readonly ModuleContractInput[]): string {
  const lines = ['# Generated contracts', '', '> Generated by `pnpm generate`. Do not edit.', ''];
  for (const contract of contracts) {
    lines.push(`## ${contract.id}`, '');
    lines.push('| Surface | Names |', '|---|---|');
    lines.push(`| State | ${Object.keys(contract.state).sort().join(', ') || 'none'} |`);
    lines.push(`| NUI events to NUI | ${Object.keys(contract.nui.events.toNui).sort().join(', ') || 'none'} |`);
    lines.push(`| NUI events to client | ${Object.keys(contract.nui.events.toClient).sort().join(', ') || 'none'} |`);
    lines.push(`| NUI RPC to NUI | ${Object.keys(contract.nui.rpc.toNui).sort().join(', ') || 'none'} |`);
    lines.push(`| NUI RPC to client | ${Object.keys(contract.nui.rpc.toClient).sort().join(', ') || 'none'} |`);
    lines.push(`| Network RPC client to server | ${Object.keys(contract.net.rpc.clientToServer).sort().join(', ') || 'none'} |`);
    lines.push(`| Client exports | ${Object.keys(contract.exports.client).sort().join(', ') || 'none'} |`);
    lines.push(`| Server exports | ${Object.keys(contract.exports.server).sort().join(', ') || 'none'} |`, '');
  }
  if (lines.at(-1) === '') {
    lines.pop();
  }
  return `${lines.join('\n')}\n`;
}

export function renderArtifacts(
  inputContracts: readonly ModuleContractInput[]
): ReadonlyMap<string, string> {
  const contracts = [...inputContracts].sort((left, right) => left.id.localeCompare(right.id));
  const moduleIds = new Set<string>();
  const moduleIdentifiers = new Map<string, string>();
  const publicExportNames = {
    client: new Map<string, string>(),
    server: new Map<string, string>(),
  };
  for (const contract of contracts) {
    if (moduleIds.has(contract.id)) {
      throw new TypeError(`Duplicate module contract id: ${contract.id}`);
    }
    moduleIds.add(contract.id);
    const identifier = pascal(contract.id);
    const previousIdentifier = moduleIdentifiers.get(identifier);
    if (previousIdentifier !== undefined) {
      throw new TypeError(
        `Generated module identifier collision: ${previousIdentifier} and ${contract.id} both generate ${identifier}`
      );
    }
    moduleIdentifiers.set(identifier, contract.id);
    for (const side of ['client', 'server'] as const) {
      for (const method of Object.keys(contract.exports[side])) {
        const exportName = `${contract.id}_${method}`;
        const previous = publicExportNames[side].get(exportName);
        if (previous) {
          throw new TypeError(
            `Public export name collision on ${side}: ${previous} and ${contract.id}.${method} both generate ${exportName}`
          );
        }
        publicExportNames[side].set(exportName, `${contract.id}.${method}`);
      }
    }
  }
  const artifacts = new Map<string, string>();
  const registry = `${HEADER_LUA}LR = LR or {}\nLR.Generated = LR.Generated or {}\nLR.Generated.Contracts = LR.Generated.Contracts or {}\n`;
  for (const side of ['shared', 'client', 'server'] as const) {
    artifacts.set(`${side}/generated/contracts.lua`, registry);
  }
  for (const contract of contracts) {
    for (const side of ['shared', 'client', 'server'] as const) {
      artifacts.set(
        `${side}/generated/contracts/${contract.id}.lua`,
        renderRuntimeContract(contract, side)
      );
    }
    artifacts.set(`types/shared/generated/${contract.id}.d.lua`, renderSharedTypes(contract));
    artifacts.set(`types/client/generated/${contract.id}.d.lua`, renderClientTypes(contract));
    artifacts.set(`types/server/generated/${contract.id}.d.lua`, renderServerTypes(contract));
    artifacts.set(
      `packages/contracts/src/modules/${contract.id}.contract.ts`,
      renderContractModule(contract)
    );
  }
  artifacts.set(
    'packages/contracts/src/modules/index.ts',
    renderContractModuleIndex(contracts)
  );
  artifacts.set('web/src/generated/contracts.ts', renderWeb(contracts));
  artifacts.set('docs/generated/contracts.md', renderDocs(contracts));

  return new Map(
    [...artifacts.entries()]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([path, content]) => [path, content.replace(/\r\n/g, '\n')])
  );
}

export function stableContractJson(contract: ModuleContractInput): string {
  return `${JSON.stringify(sortJson(contract), null, 2)}\n`;
}
