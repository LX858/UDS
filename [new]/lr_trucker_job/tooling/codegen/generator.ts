type Side = 'client' | 'server' | 'shared';
type JsonRecord = Record<string, unknown>;

const HEADER_LUA = '-- Generated by tooling/codegen. Do not edit.\n';
const HEADER_META = '---@meta\n-- Generated by tooling/codegen. Do not edit.\n\n';
const HEADER_TS = '/* Generated by tooling/codegen. Do not edit. */\n';

